def efficiency_columns(df: pd.DataFrame) -> dict:
    """Efficiency columns in order of preference (full-precision timing first when present)."""
    def present(*names):
        return [n for n in names if n in df.columns]
    return {
        "b1_mean": present("b1_mean_latency_ms_full", "b1_mean_latency_ms"),
        "b1_median": present("b1_median_latency_ms_full", "b1_median_latency_ms"),
        "b8_throughput": present("b8_aggregate_throughput_full", "b8_aggregate_throughput_samples_per_s"),
    }


def first_value(row, columns):
    """First non-missing value among the given columns of a row."""
    for column in columns:
        value = row[column]
        if not _is_missing(value):
            return float(value)
    return float("nan")


def efficiency_table(df: pd.DataFrame) -> pd.DataFrame:
    """Latency, throughput and incremental peak memory (bytes / 2**20 = MiB) per context."""
    cols = efficiency_columns(df)
    df = df.copy()
    df["_arch"] = df["architecture"].map(rio.architecture_key)
    df["_arch_rank"] = df["_arch"].map({a: i for i, a in enumerate(rio.ARCH_ORDER)})
    df["_prec"] = df["precision"].map(rio.precision_label)
    df = df.sort_values(["_arch_rank", "_prec"], ascending=[True, False]).reset_index(drop=True)
    rows = []
    for _, r in df.iterrows():
        rows.append({"Architecture": rio.ARCH_LABELS.get(r["_arch"], r["_arch"]), "Precision": r["_prec"],
                     "B1 mean (ms)": fmt(first_value(r, cols["b1_mean"]), 3),
                     "B1 median (ms)": fmt(first_value(r, cols["b1_median"]), 3),
                     "B8 throughput (images/s)": fmt(first_value(r, cols["b8_throughput"]), 3),
                     "B1 peak (MiB)": fmt(float(r["b1_incremental_peak_allocated_bytes"]) / 2 ** 20, 3),
                     "B8 peak (MiB)": fmt(float(r["b8_incremental_peak_allocated_bytes"]) / 2 ** 20, 3)})
    return pd.DataFrame(rows)


CONTRAST_LABELS = {"capacity_contrast": "ResNet50 $-$ ResNet18",
                   "efficient_vs_high_capacity": "EfficientNet-B0 $-$ ResNet50",
                   "deployment_vs_high_capacity": "MobileNetV3-Large $-$ ResNet50"}


def stats_table(df: pd.DataFrame, config, block_length: int | None = 16) -> pd.DataFrame:
    """Contrast estimates, 95 % bootstrap intervals, raw and Holm p-values for one block length."""
    df = df.copy()
    if block_length is not None:
        df = df[df["block_length"].astype(int) == int(block_length)]
    df["_metric_rank"] = df["metric"].map({"macro_f1": 0, "balanced_accuracy": 1})
    df["_contrast_rank"] = df["contrast"].map({k: i for i, k in enumerate(CONTRAST_LABELS)})
    df = rio.add_labels(df, config).sort_values(["_task_rank", "_metric_rank", "_contrast_rank"])
    rows = []
    for _, r in df.iterrows():
        rows.append({"Task": r["task_label"], "Metric": rio.METRIC_LABELS.get(r["metric"], r["metric"]),
                     "Contrast": CONTRAST_LABELS.get(r["contrast"], r["contrast"]),
                     "Difference": fmt(r["estimate"]),
                     "95\\% CI": f"[{fmt(r['ci95_low'])}, {fmt(r['ci95_high'])}]",
                     "p": fmt(r["raw_p"]), "Holm p": fmt(r["holm_p"])})
    return pd.DataFrame(rows)


BASELINE_NAMES = {"B0": "Majority", "B1": "Linear SVM", "B2": "Random forest"}


def baselines_table(df: pd.DataFrame, config) -> pd.DataFrame:
    """Baseline metrics per task; random-forest values are mean and SD over three seeds."""
    df = rio.add_labels(df, config).sort_values(["_task_rank", "baseline"])
    rows = []
    for _, r in df.iterrows():
        rows.append({"Task": r["task_label"], "Baseline": BASELINE_NAMES.get(str(r["baseline"]), r["baseline"]),
                     **{rio.METRIC_LABELS[m]: fmt_pm(r[m], r[f"{m}_sd"])
                        for m in ("macro_f1", "balanced_accuracy", "auroc", "auprc")}})
    return pd.DataFrame(rows)


def split_table(df: pd.DataFrame, config) -> pd.DataFrame:
    df = rio.add_labels(df, config).sort_values("_task_rank")
    rows = []
    for _, r in df.iterrows():
        rows.append({"Task": r["task_label"], "Train": int(r["train_n"]), "Validation": int(r["val_n"]),
                     "Test": int(r["test_n"]), "Test Good": int(r["test_good"]), "Test Defect": int(r["test_defect"])})
    return pd.DataFrame(rows)


def write(frame: pd.DataFrame, out_dir: Path, stem: str, align: str, source: str, csv_frame: pd.DataFrame | None = None) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    tex = out_dir / f"{stem}.tex"
    csv_path = out_dir / f"{stem}.csv"
    tex.write_text(latex_tabular(frame, align, source), encoding="utf-8")
    plain = (csv_frame if csv_frame is not None else frame).copy()
    for column in plain.columns:
        if plain[column].dtype == object:
            plain[column] = plain[column].map(plain_text)
    plain.columns = [plain_text(c) for c in plain.columns]
    plain.to_csv(csv_path, index=False, encoding="utf-8", lineterminator="\n")
    return [tex, csv_path]


def make_all(results_dir: Path, out_dir: Path, config) -> dict:
    """Create every table whose source CSV exists; return {table stem: status}."""
    status = {}

    def run(stem, source, builder):
        frame = rio.load(source, results_dir)
        if frame is None:
            status[stem] = f"skipped (results/{source} not found)"
            return
        builder(frame)
        status[stem] = "written"

    run("table_splits", "split_counts.csv",
        lambda f: write(split_table(f, config), out_dir, "table_splits", "lrrrrr", "split_counts.csv"))

    def predictive(f):
        tex, plain = predictive_table(f, config)
        write(tex, out_dir, "table_predictive", "llr" + "c" * 6, "predictive_groups.csv", plain)
    run("table_predictive", "predictive_groups.csv", predictive)

    def calibration(f):
        directions, joint = calibration_tables(f, config)
        write(directions, out_dir, "table_calibration_directions", "llrrrr", "calibration_groups.csv")
        write(joint, out_dir, "table_calibration_joint", "lr", "calibration_groups.csv")
    run("table_calibration", "calibration_groups.csv", calibration)

    run("table_uncertainty", "uq_summary.csv",
        lambda f: write(uncertainty_table(f), out_dir, "table_uncertainty", "lrrrrrrrr", "uq_summary.csv"))
    run("table_robustness", "robustness_direction.csv",
        lambda f: write(robustness_table(f), out_dir, "table_robustness", "llccc", "robustness_direction.csv"))
    run("table_xai_threshold_free", "xai_threshold_free.csv",
        lambda f: write(xai_threshold_free_table(f), out_dir, "table_xai_threshold_free", "lllr" + "c" * 6,
                        "xai_threshold_free.csv"))
    run("table_xai_overlap", "xai_overlap.csv",
        lambda f: write(xai_overlap_table(f), out_dir, "table_xai_overlap", "lllc" + "c" * 4, "xai_overlap.csv"))
    run("table_efficiency", "efficiency.csv",
        lambda f: write(efficiency_table(f), out_dir, "table_efficiency", "llrrrrr", "efficiency.csv"))
    run("table_stats", "stats_tests.csv",
        lambda f: write(stats_table(f, config), out_dir, "table_stats", "lllrlrr", "stats_tests.csv"))
    run("table_baselines", "baselines.csv",
        lambda f: write(baselines_table(f, config), out_dir, "table_baselines", "llcccc", "baselines.csv"))
    return status
